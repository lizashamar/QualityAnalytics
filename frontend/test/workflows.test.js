import assert from 'node:assert/strict';
globalThis.window = {location:{search:'?api=http://localhost/api&mock=0'}};
const { store } = await import('../js/store.js');
const { criterionModalView, handlers, scaleMode } = await import('../js/components/checklist-editor.js');
const { api } = await import('../js/api.js');
const draft = {criteria:[]};
const criterion = {id:'new',section:'Quality',title:'Resolution',question:'Describe resolution',type:'yesno',weight:100,allow_na:false,na_condition:'',scale_steps:[],scale_labels:{},is_flag:false};
store.set({draft,modal:{type:'criterion',index:-1,c:criterion}});
const fields = {'cm-id':{value:'resolution'},'cm-title':{value:'Resolution'},'cm-section':{value:'Quality'},'cm-question':{value:'Describe resolution'},'cm-flag':{checked:false},'cm-type':{value:'scale_20'},'cm-weight':{value:'100'},'cm-na':{checked:false}};
globalThis.document = {getElementById:(id)=>fields[id] || null};
handlers.submit.criterion();
const saved = store.get().draft.criteria[0];
assert.equal(saved.id,'resolution');
assert.equal(saved.type,'scale');
assert.equal(saved.scale_steps.length,21);
assert.equal(scaleMode(saved),'scale_20');
assert.ok(String(criterionModalView(store.get(),{index:0,c:saved})).includes('ID критерия'));
assert.ok(String(criterionModalView(store.get(),{index:0,c:saved})).includes('Шкала 0–10'));
const calls=[];
globalThis.fetch = async (url,opts) => {
  calls.push({url,opts});
  return {ok:true,status:200,json:async()=>url.endsWith('/datasets/import') ? {imported:65,total:65,skipped:0} : []};
};
await api.importDataset('CONTROL &23');
await api.getConversations();
await api.listEvaluations();
assert.equal(JSON.parse(calls[0].opts.body).group_id,'CONTROL &23');
assert.ok(calls[1].url.includes('group_id=CONTROL+%2623'));
assert.ok(calls[2].url.includes('group_id=CONTROL+%2623'));
console.log('Checklist/control checks passed: criterion form, full scales, ID editing, group propagation');

const { runEvaluation, resolveAppeal } = await import('../js/actions.js');
const current = {id:'ev-action',conversation_id:'call',items:[],final_total:90};
const resolved = {id:'AP-action',evaluation_id:current.id,status:'resolved',resolution:{new_answer:10,reason:'Reviewed'}};
globalThis.fetch = async (url,opts) => ({ok:true,status:200,json:async()=>{
  if (url.endsWith('/resolve')) return resolved;
  if (url.endsWith('/appeals')) return [{id:'AP-old',status:'outdated'}];
  return current;
}});
store.set({evaluations:{},latest:{},appeals:[{id:resolved.id,status:'pending'}]});
await runEvaluation('call','checklist');
assert.equal(store.get().appeals[0].status,'outdated');
assert.equal(store.get().latest.call,current.id);
store.set({appeals:[{id:resolved.id,status:'pending'}]});
await resolveAppeal(resolved.id,{new_answer:10,reason:'Reviewed'});
assert.equal(store.get().appeals[0].status,'resolved');
assert.equal(store.get().evaluations[current.id].final_total,90);
console.log('Action checks passed: reevaluation refreshes stale appeals; review refreshes persisted score');

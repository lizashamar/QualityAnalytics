ROLE_ALIASES = {"client", "operator", "bot", "system"}


def _one_line(s: str) -> str:
    return re.sub(r"\s*\n\s*", " / ", str(s or "")).strip()


def criteria_for_prompt(criteria: list[dict]) -> list[dict]:
    keys = ("id", "section", "title", "question", "type", "weight", "allow_na", "na_condition", "scale_steps", "scale_labels", "is_flag")
    out = []
    for c in criteria:
        d = {k: c.get(k) for k in keys}
        if d["type"] != "scale":
            d.pop("scale_steps"), d.pop("scale_labels")
        if not d["allow_na"]:
            d.pop("na_condition")
        out.append(d)
    return out


def reaction_fact(t: list[dict]) -> str:
    sec, start, op = first_operator_reaction(t)
    if op is None:
        return "Оператор в диалоге не отвечал."
    if sec is None:
        return f"Первая реплика оператора — [{op}]; время реакции по меткам вычислить не удалось."
    verdict = "в пределах порога 3 мин" if sec <= 180 else "ПРЕВЫШЕН порог 3 мин"
    return f"Первая реплика оператора — [{op}], через {int(round(sec))} с после [{start}] ({verdict})."


def build_user_prompt(conv: dict, criteria: list[dict]) -> str:
    t = conv.get("transcript") or []
    lines = [f"[{i}] {r.get('speaker')} ({r.get('timestamp')}): {_one_line(r.get('text'))}" for i, r in enumerate(t)]
    return (
        f"Язык диалога: {conv.get('language')}\n"
        f"Канал: {conv.get('channel')}\n"
        f"Реплик: {len(t)} (индексы 0..{max(0, len(t) - 1)})\n"
        f"Первая реакция: {reaction_fact(t)}\n\n"
        "ТРАНСКРИПТ:\n" + "\n".join(lines) + "\n\n"
        "КРИТЕРИИ (JSON):\n" + json.dumps(criteria_for_prompt(criteria), ensure_ascii=False) + "\n\n"
        "Оцени оператора по каждому критерию и верни JSON в описанном формате."
    )


_LINE = re.compile(r"^\[(\d+)\] (\w+) \((.*?)\): (.*)$")


def parse_user_prompt(user: str) -> tuple[str, list[dict], list[dict]]:
    """Обратный разбор (для mock-провайдера): язык, транскрипт, критерии."""
    lang = re.search(r"^Язык диалога: (.*)$", user, re.M)
    tr_part = user.split("ТРАНСКРИПТ:\n", 1)[1].split("\n\nКРИТЕРИИ (JSON):\n", 1)
    transcript = []
    for line in tr_part[0].splitlines():
        m = _LINE.match(line)
        if m:
            transcript.append({"index": int(m.group(1)), "speaker": m.group(2), "timestamp": m.group(3), "text": m.group(4)})
    crit_json = tr_part[1].split("\n\n", 1)[0]
    return (lang.group(1).strip() if lang else ""), transcript, json.loads(crit_json)
